def t(key: str, lang: str = "no", **kwargs) -> str:
    """Return translated string for key in lang, falling back to 'no'."""
    text = TRANSLATIONS.get(lang, {}).get(key)
    if text is None:
        text = TRANSLATIONS.get("no", {}).get(key, key)
    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, ValueError):
            pass
    return text


def theme_label(theme_no: str, lang: str = "no") -> str:
    """Return translated display name for a Norwegian theme name."""
    key = THEME_KEY_MAP.get(theme_no)
    if not key:
        return theme_no
    return t(key, lang)
